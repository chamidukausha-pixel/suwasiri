  static String _id(String prefix, String district, String name) {
    final slug = '$district-$name'
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]+'), '-')
        .replaceAll(RegExp(r'-+'), '-')
        .replaceAll(RegExp(r'^-|-$'), '');
    return '$prefix-$slug';
  }

  static ClinicFacility _moh(String district, String area, [String? address]) {
    return ClinicFacility(
      id: _id('moh', district, area),
      name: 'MOH Office, $area',
      district: district,
      type: FacilityType.mohClinic,
      address: address ?? '$area, $district District',
      hours: _mohHours,
    );
  }

  static ClinicFacility _gov(String district, String name, [String? address]) {
    return ClinicFacility(
      id: _id('hosp', district, name),
      name: name,
      district: district,
      type: FacilityType.hospital,
      address: address ?? '$district District',
      hours: _govHours,
    );
  }

  static ClinicFacility _priv(
    String district,
    String name, {
    String? address,
    int priceLkr = 7500,
  }) {
    return ClinicFacility(
      id: _id('priv', district, name),
      name: name,
      district: district,
      type: FacilityType.privateHospital,
      address: address ?? '$district District',
      hours: _privHours,
      priceLkr: priceLkr,
    );
  }

